'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const css = fs.readFileSync(path.join(root, 'assets/css/app.css'), 'utf8');
const ui = fs.readFileSync(path.join(root, 'assets/js/upcoming-launch-browser.js'), 'utf8');
const engine = fs.readFileSync(path.join(root, 'assets/js/upcoming-launch-filters.js'), 'utf8');
const countryMap = JSON.parse(fs.readFileSync(path.join(root, 'data/country_codes.json'), 'utf8'));

assert.match(html, /id="upcomingLaunchesBtn"[\s\S]*aria-controls="globalLaunchDialog"/);
assert.match(html, /<dialog id="globalLaunchDialog"[\s\S]*aria-labelledby="globalLaunchTitle"/);
for (const days of ['7', '14', '30', '120']) assert.match(html, new RegExp('data-days="' + days + '"'));
assert.match(html, /<select id="globalLaunchCountryBasis"[\s\S]*value="operator"[\s\S]*value="site"/);
assert.match(html, /id="globalLaunchCountryOptions"[\s\S]*role="group"/);
assert.match(html, /id="globalLaunchSelectedCountries"/);
assert.match(html, /id="globalLaunchResultCount"/);
assert.match(html, /id="globalLaunchReload"/);
assert.ok(html.indexOf('assets/js/app.js?') < html.indexOf('assets/js/upcoming-launch-filters.js?'));
assert.ok(html.indexOf('assets/js/upcoming-launch-filters.js?') < html.indexOf('assets/js/upcoming-launch-browser.js?'));
assert.match(css, /@media\(max-width:760px\)[\s\S]*?\.global-launch-content\{grid-template-columns:minmax\(0,1fr\)/);
assert.match(ui, /fa:\s*\{/); assert.match(ui, /en:\s*\{/); assert.match(ui, /ar:\s*\{/);
assert.match(ui, /aria-checked=/); assert.match(ui, /aria-pressed/);
assert.match(ui, /Filters\.filterLaunches\(/);
assert.match(engine, /function filterEvents\(/); assert.match(engine, /function filterLaunches\(/);
assert.equal(countryMap.countries.length, 249);
assert.equal(countryMap.aliases.US, 'USA');
assert.equal(countryMap.countries.find(x => x.code === 'ISR').fa, 'فلسطین اشغالی');
console.log('PASS: worldwide upcoming-launch UI markup, responsive layout, 3-language copy, script order and 249-country index');
