#!/usr/bin/env python3
"""Mirror public Mapzen/AWS Terrarium z2 elevation tiles beside the RASPEHR 3D module.

Run on a computer/server with outbound internet, before deploying. Only 16 global
z2 tiles are needed. No synthetic elevation data is bundled as real terrain.
The utility validates dimensions and writes atomically; it does not change 2D map code.
"""
from __future__ import annotations
from concurrent.futures import ThreadPoolExecutor, as_completed
from pathlib import Path
from urllib.request import Request, urlopen
from urllib.error import URLError
import hashlib
import json
import os
import shutil
import struct
import tempfile
import time

BASE_URL = "https://s3.amazonaws.com/elevation-tiles-prod/terrarium/2/"
TILE_COUNT = 16
HERE = Path(__file__).resolve().parent.parent
DEST = HERE / "assets" / "dem" / "terrarium" / "2"
CONFIG = HERE / "assets" / "js" / "terrain-source.js"
SOURCE = "https://registry.opendata.aws/terrain-tiles/"
ATTRIBUTION = "https://github.com/tilezen/joerd/blob/master/docs/attribution.md"


def inspect_png(payload: bytes) -> tuple[int, int]:
    if len(payload) < 33 or payload[:8] != b"\x89PNG\r\n\x1a\n" or payload[12:16] != b"IHDR":
        raise ValueError("Missing valid PNG header/IHDR")
    width, height = struct.unpack(">II", payload[16:24])
    if width != 256 or height != 256:
        raise ValueError(f"Incorrect Terrarium tile dimensions: {width}x{height}")
    if not payload.endswith(b"IEND\xaeB`\x82"):
        raise ValueError("Incomplete PNG stream (missing IEND)")
    return width, height


def download_tile(x: int, y: int) -> tuple[int, int, bytes]:
    url = f"{BASE_URL}{x}/{y}.png"
    error = None
    for attempt in range(3):
        try:
            request = Request(url, headers={"User-Agent":"RASPEHR-Stage1-terrain-setup/1.0"})
            with urlopen(request, timeout=20) as response:
                content = response.read(3_000_000)
            inspect_png(content)
            return x, y, content
        except (URLError, ValueError, TimeoutError, OSError) as exc:
            error = exc
            if attempt < 2:
                time.sleep(0.8 * (attempt + 1))
    raise RuntimeError(f"DEM 2/{x}/{y}: {error}")


def run() -> None:
    destination_parent = DEST.parent
    destination_parent.mkdir(parents=True, exist_ok=True)
    temp = Path(tempfile.mkdtemp(prefix="dem-z2-", dir=destination_parent))
    hashes = {}
    try:
        with ThreadPoolExecutor(max_workers=4) as pool:
            futures = [pool.submit(download_tile, x, y) for y in range(4) for x in range(4)]
            for future in as_completed(futures):
                x, y, payload = future.result()
                folder = temp / str(x)
                folder.mkdir(parents=True, exist_ok=True)
                (folder / f"{y}.png").write_bytes(payload)
                hashes[f"2/{x}/{y}.png"] = hashlib.sha256(payload).hexdigest()
        if len(hashes) != TILE_COUNT:
            raise RuntimeError("Missing tiles; install aborted")
        manifest = {
            "source":SOURCE,"attribution":ATTRIBUTION,"encoding":"Terrarium RGB",
            "zoom":2,"total_tiles":TILE_COUNT,"sha256":dict(sorted(hashes.items()))
        }
        (temp / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
        # Create final tree only once all downloads and validations succeed.
        backup = destination_parent / (DEST.name + '.previous')
        if backup.exists(): shutil.rmtree(backup)
        if DEST.exists(): DEST.rename(backup)
        try:
            temp.rename(DEST)
        except Exception:
            if backup.exists() and not DEST.exists(): backup.rename(DEST)
            raise
        if backup.exists(): shutil.rmtree(backup)
        CONFIG.write_text(
            "/* Generated by fetch_dem_z2.py: serve locally with RASPEHR. */\n"
            "window.RASPEHR_TERRAIN_URL = 'assets/dem/terrarium/';\n",
            encoding="utf-8",
        )
        print(f"SUCCESS: {TILE_COUNT} verified Terrarium tiles saved in {DEST}")
        print("Publish assets/dem/terrarium/ and assets/js/terrain-source.js together.")
    finally:
        if temp.exists(): shutil.rmtree(temp)


if __name__ == '__main__':
    run()
