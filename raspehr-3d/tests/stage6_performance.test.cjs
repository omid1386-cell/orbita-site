'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const window={navigator:{deviceMemory:2,hardwareConcurrency:4,connection:{saveData:true}},innerWidth:390,matchMedia:q=>({matches:q==='(pointer: coarse)'})};
const src=fs.readFileSync(path.join(root,'assets/js/stage6-performance.js'),'utf8');
vm.runInNewContext(src,{window});
const P=window.RaspehrStage6Performance;
assert.equal(P.policy(P.hints(),'auto').mode,'economy');
assert.equal(P.policy(P.hints(),'auto').quality,'low');
assert.equal(P.policy(P.hints(),'auto').prefetch,false);
assert.equal(P.policy(P.hints(),'auto').fps,30);
assert.equal(P.policy({width:1366,memory:16,cores:12},'auto').mode,'balanced');
assert.equal(P.policy({width:390,memory:2,cores:4},'detail').quality,'balanced','prevent unbounded 8K on low-end mobile');
assert.equal(P.policy({width:900,memory:4,cores:8},'balanced').quality,'balanced');
assert.equal(P.policy({width:1100,memory:8,cores:8,saveData:true},'auto').mode,'economy');
assert.equal(P.policy({width:1100,memory:8,cores:8},'bogus').requestedMode,'auto');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(html,/id="performanceMode"/);assert.match(html,/id="performanceStatus"/);
assert.ok(html.indexOf('stage6-performance.js')<html.indexOf('globe-engine.js'));
const engine=fs.readFileSync(path.join(root,'assets/js/globe-engine.js'),'utf8');
assert.match(engine,/setPerformanceMode\(mode\)/);
assert.match(engine,/setActive\(value\)/);
console.log('PASS Stage6 performance policy, device caps, quality profile and HTML wiring');
