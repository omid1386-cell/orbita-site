'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const source = fs.readFileSync(path.resolve(__dirname,'../assets/js/terrain-dem.js'),'utf8');
const context = {window:{},console};
vm.runInNewContext(source,context);
const {TerrariumElevation,mercatorPoint,terrariumMeters,applyHeightToGeometry,ZOOM} = context.window.RaspehrTerrainDEM;
assert.equal(ZOOM,2);
assert.equal(terrariumMeters(135,208,0),2000);
assert.equal(terrariumMeters(126,12,0),-500);
assert.equal(terrariumMeters(128,0,0),0);
let p=mercatorPoint(0,0,2);
assert.equal(p.tx,2);assert.equal(p.ty,2);
p=mercatorPoint(40,40,2);
assert.ok(p.tx>=0&&p.tx<4&&p.ty>=0&&p.ty<4);
p=mercatorPoint(-40,-80,2);
assert.ok(p.tx>=0&&p.tx<4&&p.ty>=0&&p.ty<4);
const datum=new TerrariumElevation(2);
const tile=new Uint8ClampedArray(256*256*4);
for(let i=0;i<tile.length;i+=4){tile[i]=135;tile[i+1]=208;tile[i+2]=0;tile[i+3]=255;}
for(let y=0;y<4;y++)for(let x=0;x<4;x++)datum.tiles.set(`${x}/${y}`,tile);
for(const [lat,lon] of [[0,0],[55,40],[-60,150],[75,-150]])assert.ok(Math.abs(datum.meters(lat,lon)-2000)<0.01);
assert.equal(datum.meters(89,0),0,'Mercator poles are outside grid');
const positions=Float32Array.from([1.72,0,0,0,1.72,0,0,0,1.72]);
const geom={attributes:{position:{array:positions,count:3,needsUpdate:false}},userData:{},computeVertexNormals(){this.normalsUpdated=true;},computeBoundingSphere(){this.boundsUpdated=true;}};
let stats=applyHeightToGeometry(geom,datum,1.72,4);
assert.equal(stats.vertices,3);
assert.equal(stats.displaced,2,'polar vertex at 90N excluded');
assert.ok(positions[0]>1.72,'positive DEM should raise surface');
assert.ok(stats.maxElevationMeters>1999);
const risen=positions[0];
applyHeightToGeometry(geom,datum,1.72,1);
assert.ok(positions[0]<risen,'decrease exaggeration lowers vertex');
applyHeightToGeometry(geom,null,1.72,4);
assert.ok(Math.abs(positions[0]-1.72)<1e-5,'disabling terrain restores original positions');
assert.equal(geom.normalsUpdated,true);
assert.equal(geom.boundsUpdated,true);
const engineSource=fs.readFileSync(path.resolve(__dirname,'../assets/js/globe-engine.js'),'utf8');
const controllerSource=fs.readFileSync(path.resolve(__dirname,'../assets/js/prototype.js'),'utf8');
const html=fs.readFileSync(path.resolve(__dirname,'../index.html'),'utf8');
assert.match(html,/assets\/js\/terrain-dem\.js/);
assert.match(html,/id="terrain"/);
assert.match(html,/id="terrainExaggeration"/);
assert.match(engineSource,/applyTerrainGeometry/);
assert.match(engineSource,/enableTerrain/);
assert.match(controllerSource,/terrain-ready/);
console.log('PASS terrain DEM: Terrarium conversion, Mercator coordinates, elevation sampling, vertex displacement, restoration.');
